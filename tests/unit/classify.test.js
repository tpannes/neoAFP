/**
 * Tests for file classification (task T013): every file kind of the data model, recognized by
 * content only (FR-003), including special cases seen in real files.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createWorkspace, createBufferSource } from '../../src/lib/index.js';
import {
  bytes, field, group, documentOf, page, nop, resourceGroup, resource, withSeparators, ebcdic,
  uint, ID,
} from '../helpers/afp-builder.js';

/**
 * Classifies bytes through a workspace.
 * @param {Uint8Array} data File content.
 * @param {string} [name] File name (must not influence the result).
 * @returns {Promise<{file: object, diagnostics: object[]}>} The file summary and its diagnostics.
 */
async function classify(data, name = 'file.bin') {
  const ws = createWorkspace();
  const [file] = await ws.addFiles([createBufferSource(data, name)], 'file');
  return { file, diagnostics: ws.getDiagnostics({ fileId: file.id }) };
}

const DOC = documentOf('DOC1', page('PAGE1'));
const codePage = group(ID.BCP, 'T1NEOCP2', field('D3A687', [0, 0]));

/**
 * Builds line data records with record descriptor words (2-byte length, 2 zero bytes).
 * @param {Uint8Array[]} records Record contents.
 * @returns {Uint8Array} RDW-prefixed records.
 */
function rdw(...records) {
  return bytes(...records.map((r) => bytes(uint(r.length + 4, 2), 0, 0, r)));
}

const cases = [
  ['document', DOC, 'document'],
  ['page segment', group(ID.BPS, 'S1TEST'), 'pageSegment'],
  ['overlay', group(ID.BMO, 'O1TEST'), 'overlay'],
  ['font character set', group(ID.BFN, 'C0TEST'), 'fontCharacterSet'],
  ['code page', codePage, 'codePage'],
  ['coded font', group(ID.BCF, 'X0TEST'), 'codedFont'],
  ['form definition', group(ID.BFM, 'F1TEST'), 'formDefinition'],
  ['other resource (image object)', group(ID.BIM, 'IMG1'), 'otherResource'],
  ['resource group only', resourceGroup(resource('S1A', 0xfc, group(ID.BPS, 'S1A'))), 'resourceGroup'],
  ['page definition', group(ID.BPM, 'P1TEST'), 'unsupported:pageDefinition'],
  ['line data with RDW', rdw(ebcdic(' LINE ONE'), ebcdic('0LINE TWO'), ebcdic(' LINE THREE')), 'unsupported:lineData'],
  ['mixed mode with RDW', rdw(ebcdic(' LINE ONE'), field(ID.NOP, ebcdic('X')), ebcdic(' LINE TWO')), 'unsupported:mixedMode'],
  ['line data as ASCII text lines', new TextEncoder().encode(' line one\n0line two\n line three\n1line four\n'), 'unsupported:lineData'],
];

for (const [name, data, kind] of cases) {
  test(`recognizes ${name}`, async () => {
    const { file } = await classify(data);
    assert.equal(file.kind, kind);
  });
}

test('the file name and extension are ignored', async () => {
  assert.equal((await classify(DOC, 'font.CHS')).file.kind, 'document');
  assert.equal((await classify(group(ID.BPS, 'S1X'), 'letter.afp')).file.kind, 'pageSegment');
});

test('records separated by CR/LF are classified normally', async () => {
  const { file, diagnostics } = await classify(withSeparators(DOC, [0x0d, 0x0a]));
  assert.equal(file.kind, 'document');
  assert.equal(file.recordFormat, 'lineBreaks');
  assert.equal(diagnostics.filter((d) => d.code === 'truncated').length, 0);
});

test('a file damaged by a text-mode transfer (X\'DC\' instead of X\'5A\') is not recognized', async () => {
  const damaged = Uint8Array.from([0xdc, 0x00, 0x07, 0x4c, 0x79, 0x69, 0x00, 0x00, 0x01, 0x0d, 0x0a]);
  const { file } = await classify(damaged);
  assert.equal(file.kind, 'notRecognized');
  assert.equal(file.skipReason, 'unknownEncoding');
});

test('a standalone ICC profile is not recognized', async () => {
  const icc = new Uint8Array(132);
  icc.set([0x00, 0x00, 0x02, 0x00], 0);
  icc.set(new TextEncoder().encode('acsp'), 36);
  const { file } = await classify(icc, 'profile.icc');
  assert.equal(file.kind, 'notRecognized');
  assert.equal(file.skipReason, 'notAfp');
});

test('documents starting with Begin Print File, resource group, document index or NOPs', async () => {
  const withPrintFile = group(ID.BPF, 'PF1', resourceGroup(), DOC);
  const withResourceGroup = bytes(resourceGroup(resource('X0A', 0x40, group(ID.BCF, 'X0A'))), DOC);
  const withIndex = bytes(group(ID.BDI, 'IDX1', field('D3B2A7', [1, 2])), DOC);
  const withNops = bytes(nop('generated by test'), nop('second comment'), DOC);
  for (const data of [withPrintFile, withResourceGroup, withIndex, withNops]) {
    assert.equal((await classify(data)).file.kind, 'document');
  }
});

test('a resource file starting with Begin Resource gets the type of the enclosed object', async () => {
  const { file } = await classify(resource('T1NEOCP3', 0x41, codePage));
  assert.equal(file.kind, 'codePage');
});

test('a file with only NOP fields is skipped without an error, listed with an info entry', async () => {
  const { file, diagnostics } = await classify(bytes(nop('only a comment')));
  assert.equal(file.kind, 'notRecognized');
  assert.equal(file.skipReason, 'onlyComments');
  assert.deepEqual(diagnostics.map((d) => [d.severity, d.code, d.params.reason]), [['info', 'unsupportedFileKind', 'onlyComments']]);
});

for (const [name, magic] of [['TrueType', [0, 1, 0, 0]], ['TrueType (Mac)', [...'true'].map((c) => c.charCodeAt(0))],
  ['OpenType CFF', [...'OTTO'].map((c) => c.charCodeAt(0))], ['TrueType collection', [...'ttcf'].map((c) => c.charCodeAt(0))]]) {
  test(`recognizes a ${name} font file`, async () => {
    const font = new Uint8Array(64);
    font.set(magic, 0);
    assert.equal((await classify(font, 'font.bin')).file.kind, 'truetypeFont');
  });
}

test('a text file is not recognized', async () => {
  const { file } = await classify(new TextEncoder().encode('Testübertragungsverfahren.\nFr 22 Feb\n'));
  assert.equal(file.kind, 'notRecognized');
  assert.equal(file.skipReason, 'notAfp');
});
